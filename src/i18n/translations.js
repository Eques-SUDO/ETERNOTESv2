// Keep source messages readable in components and preserve intentional spacing.
export function translate(language, message, params = {}) {
  const key = message.trim()
  const translated = language === 'fr' ? (french[key] ?? key) : key
  const leading = message.match(/^\s*/)[0]
  const trailing = message.match(/\s*$/)[0]
  return leading + translated.replace(/\{(\w+)\}/g, (match, name) =>
    Object.hasOwn(params, name) ? String(params[name]) : match
  ) + trailing
}
